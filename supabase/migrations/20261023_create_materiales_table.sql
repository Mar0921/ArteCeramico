-- Tabla de materiales del laboratorio.
-- Permite a admin y empleados registrar y subir archivos de materiales.
CREATE TABLE IF NOT EXISTS public."materiales" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo text NOT NULL UNIQUE,
  nombre text NOT NULL,
  categoria text,
  tipo_material text,
  marca_fabricante text,
  ref_fabricante text,
  material text,
  producto text,
  proveedor text,
  archivo_url text,
  archivo_nombre text,
  subido_por uuid REFERENCES auth.users(id),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE public."materiales" ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Materiales: lectura autenticados" ON public."materiales"
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Materiales: insert autenticados" ON public."materiales"
  FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Materiales: update autenticados" ON public."materiales"
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

CREATE POLICY "Materiales: delete autenticados" ON public."materiales"
  FOR DELETE TO authenticated USING (true);

-- Bucket de almacenamiento para archivos de materiales
insert into storage.buckets (id, name, public, file_size_limit, owner, allowed_mime_types)
values
  ('materiales', 'materiales', true, 52428800, '', ARRAY[
    'image/jpeg',
    'image/png',
    'image/gif',
    'application/pdf',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-excel',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'text/csv'
  ])
on conflict (id) do nothing;

drop policy if exists "Authenticated users can upload archivos materiales" on storage.objects;
drop policy if exists "Public can read archivos materiales" on storage.objects;

create policy "Authenticated users can upload archivos materiales"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'materiales');

create policy "Authenticated users can read archivos materiales"
  on storage.objects for select
  to authenticated
  using (bucket_id = 'materiales');

create policy "Public can read archivos materiales"
  on storage.objects for select
  to public
  using (bucket_id = 'materiales');
